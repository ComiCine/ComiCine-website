"""Find top-level TypeScript exports that nothing in the repository references.

Why this check exists: an export survives a refactor because no compiler or unit test fails when
its last caller disappears, and a test that keeps calling it makes the export look alive. Two
cases proved it: the status Worker kept a 404 page renderer after the real 404 moved to its
`index.ts` (only a test still called the renderer), and the generated runtime table shipped a
redirect copy object that no Functions module imported while a test asserted its keys. Neither
shows up in `tsc` or `vitest`, so the gate compares exports with callers here.

A reference is a word-boundary occurrence of the exported name in a repository source file, with
the declaration token itself masked out; callers inside the defining file count. Files under
`tests/` and `*.test.ts` / `*.spec.ts` do not count as callers, because a test-only export is dead
production code. Generated files are excluded on both sides: `functions/_data/**` and
`functions/_lib/config.ts` are outputs of `src/build.py`.

Two kinds of caller-less export are legitimate and are recorded by rule instead of by name, so
the allowlist cannot grow into a list of names nobody re-reads:

  entry point  the Pages Functions runtime calls `onRequest*`; a Worker runtime calls `export
               default`. No repository file imports either.
  test hook    a `reset*` export whose state is exercised through it by at least one test file.
               A `reset*` export that no test calls is not a hook; it is unused and fails.

USAGE is printed by `--help`.
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# Top-level exports are checked in `functions/**` and in each standalone Worker's `src/` tree.
FUNCTIONS_DIR = ROOT / "functions"
WORKERS_DIR = ROOT / "ops"

# Generated by src/build.py. An unused export there is a generator decision, not dead hand code.
GENERATED_DIRS: tuple[Path, ...] = (FUNCTIONS_DIR / "_data",)
GENERATED_FILES: tuple[Path, ...] = (FUNCTIONS_DIR / "_lib" / "config.ts",)

# Files that may call an export. `docs/` and the README are prose and must not count as callers.
# Only TypeScript and JavaScript can import an export; a Python comment is not a caller.
REFERENCE_ROOTS = (FUNCTIONS_DIR, WORKERS_DIR, ROOT / "src")
REFERENCE_SUFFIXES = {".ts", ".js"}
SKIP_DIR_NAMES = {
    "node_modules",
    ".git",
    "public",
    "preview",
    "secrets",
    ".wrangler",
    "out",
    "coverage",
    ".venv-build",
    "__pycache__",
    ".pytest_cache",
    ".ruff_cache",
}

# The Pages Functions runtime calls these by name; no repository code imports them.
ENTRY_POINT_NAMES = frozenset(
    {
        "onRequest",
        "onRequestGet",
        "onRequestPost",
        "onRequestPut",
        "onRequestPatch",
        "onRequestDelete",
        "onRequestOptions",
        "onRequestHead",
    }
)

# Test hooks follow the repository's naming convention and must be called by at least one test.
# The comment on each hook starts with "Test hook:"; the pattern is the machine-checkable form.
TEST_HOOK_PATTERN = re.compile(r"^reset[A-Z][\w$]*$")
TEST_HOOK_REASON = "test hook: clears in-memory state, called by at least one test"

# Exports that are deliberately not named reset* but exist only for a test. Each entry needs a
# reason; an entry whose export disappeared fails the gate so the table cannot rot.
TEST_ONLY_ALLOW: dict[tuple[str, str], str] = {
    ("functions/_lib/cidr.ts", "canonicalCidr"): (
        "CIDR normalisation is asserted directly by cidr.test.ts; src/build.py records the same decision"
    ),
}

USAGE = """\
python3 ops/check_unused_exports.py           gate mode: exit 1 when an unused export exists
python3 ops/check_unused_exports.py --report  print every finding; always exits 0

Scanned definitions: functions/**/*.ts and ops/*/src/**/*.ts.
Counted references:   functions, ops, and src source files; tests and generated files do not count.
Allowlisted by rule:  onRequest* entry points, export default, and reset* hooks called by a test.
Exit codes:           0 = no unused export, 1 = at least one unused export.
"""

DECLARATION = re.compile(
    r"^export\s+(?:(?:declare|abstract|async)\s+)*"
    r"(?P<kind>function|const|let|var|class|interface|type|enum|namespace)\s+"
    r"(?P<name>[A-Za-z_$][\w$]*)",
    re.MULTILINE,
)
DEFAULT_EXPORT = re.compile(r"^export\s+default\b", re.MULTILINE)
EXPORT_LIST = re.compile(
    r"^export\s+(?:type\s+)?\{(?P<body>[^}]*)\}(?:\s*from\s*[^;\n]+)?",
    re.MULTILINE,
)
NAME_PATTERN = r"(?<![\w$]){name}(?![\w$])"


@dataclass
class Export:
    name: str
    kind: str
    path: Path
    line: int
    # Character span of the exported name token in its file, masked before counting references.
    spans: tuple[tuple[int, int], ...]


@dataclass
class Finding:
    export: Export
    references: int
    test_references: int

    @property
    def relative(self) -> str:
        return self.export.path.relative_to(ROOT).as_posix()

    @property
    def reason(self) -> str:
        return "only tests call it" if self.test_references else "no caller at all"


def line_of(text: str, offset: int) -> int:
    return text.count("\n", 0, offset) + 1


def is_test_file(path: Path) -> bool:
    name = path.name
    return "tests" in path.parts or name.endswith(
        (".test.ts", ".test.js", ".test.py", ".spec.ts", ".spec.js")
    )


def is_generated(path: Path) -> bool:
    if path in GENERATED_FILES:
        return True
    return any(directory in path.parents for directory in GENERATED_DIRS)


def export_source_files() -> list[Path]:
    files = [path for path in FUNCTIONS_DIR.rglob("*.ts") if path.is_file()]
    for worker_src in WORKERS_DIR.glob("*/src"):
        if worker_src.is_dir():
            files.extend(path for path in worker_src.rglob("*.ts") if path.is_file())
    return sorted({path for path in files if not is_generated(path)})


def reference_files() -> list[Path]:
    files: list[Path] = []
    for root in REFERENCE_ROOTS:
        for path in root.rglob("*"):
            if not path.is_file() or path.suffix not in REFERENCE_SUFFIXES:
                continue
            if any(part in SKIP_DIR_NAMES for part in path.parts):
                continue
            if path == Path(__file__).resolve() or is_generated(path):
                continue
            files.append(path)
    return sorted(set(files))


def parse_exports(path: Path) -> list[Export]:
    text = path.read_text(encoding="utf-8")
    exports: list[Export] = []
    for match in DECLARATION.finditer(text):
        exports.append(
            Export(
                name=match.group("name"),
                kind=match.group("kind"),
                path=path,
                line=line_of(text, match.start("name")),
                spans=((match.start("name"), match.end("name")),),
            )
        )
    for match in DEFAULT_EXPORT.finditer(text):
        exports.append(
            Export(
                name="default",
                kind="default",
                path=path,
                line=line_of(text, match.start()),
                spans=(),
            )
        )
    for match in EXPORT_LIST.finditer(text):
        body_start = match.start("body")
        for item in match.group("body").split(","):
            exported = item.split()[-1] if item.split() else ""
            if not re.fullmatch(r"[A-Za-z_$][\w$]*", exported):
                continue
            offset = text.find(exported, body_start)
            if offset < 0:
                continue
            exports.append(
                Export(
                    name=exported,
                    kind="reexport",
                    path=path,
                    line=line_of(text, offset),
                    spans=((offset, offset + len(exported)),),
                )
            )
    return exports


def count_references(
    name: str,
    corpus: dict[Path, str],
    spans: dict[Path, tuple[tuple[int, int], ...]],
) -> tuple[int, int]:
    pattern = re.compile(NAME_PATTERN.format(name=re.escape(name)))
    used = 0
    in_tests = 0
    for path, text in corpus.items():
        if name not in text:
            continue
        found = len(pattern.findall(text))
        for start, end in spans.get(path, ()):
            found -= len(pattern.findall(text[start:end]))
        if found <= 0:
            continue
        if is_test_file(path):
            in_tests += found
        else:
            used += found
    return used, in_tests


def scan() -> tuple[list[Export], list[Finding], list[tuple[Finding, str]], list[Finding]]:
    """Return every export plus entry points, allowlisted findings (with reasons), and unused ones."""
    exports: list[Export] = []
    for path in export_source_files():
        exports.extend(parse_exports(path))

    corpus: dict[Path, str] = {
        path: path.read_text(encoding="utf-8", errors="replace") for path in reference_files()
    }
    spans_by_name: dict[str, dict[Path, tuple[tuple[int, int], ...]]] = {}
    for export in exports:
        current = spans_by_name.setdefault(export.name, {}).get(export.path, ())
        spans_by_name[export.name][export.path] = current + export.spans

    entries: list[Finding] = []
    allowed: list[tuple[Finding, str]] = []
    unused: list[Finding] = []
    for export in exports:
        if export.kind == "default" or export.name in ENTRY_POINT_NAMES:
            entries.append(Finding(export, 0, 0))
            continue
        references, test_references = count_references(
            export.name, corpus, spans_by_name[export.name]
        )
        if references:
            continue
        finding = Finding(export, references, test_references)
        key = (export.path.relative_to(ROOT).as_posix(), export.name)
        if key in TEST_ONLY_ALLOW and test_references:
            allowed.append((finding, TEST_ONLY_ALLOW[key]))
        elif TEST_HOOK_PATTERN.match(export.name) and test_references:
            allowed.append((finding, TEST_HOOK_REASON))
        else:
            unused.append(finding)
    return exports, entries, allowed, unused


def stale_allowlist_entries(exports: list[Export]) -> list[tuple[str, str]]:
    present = {(export.path.relative_to(ROOT).as_posix(), export.name) for export in exports}
    return sorted(entry for entry in TEST_ONLY_ALLOW if entry not in present)


def format_finding(finding: Finding, reason: str) -> str:
    location = f"{finding.relative}:{finding.export.line}"
    return f"  {location:<58}  {finding.export.name:<38}  {reason}"


def print_findings(
    exports: list[Export],
    entries: list[Finding],
    allowed: list[tuple[Finding, str]],
    unused: list[Finding],
) -> None:
    print(f"[unused-exports] {ROOT}")
    print(f"[unused-exports] scanned {len(export_source_files())} definition files, {len(exports)} exports")
    print(f"[unused-exports] entry points: {len(entries)}")
    print(f"[unused-exports] allowlisted caller-less exports: {len(allowed)}")
    for finding, reason in allowed:
        print(format_finding(finding, reason))
    print(f"[unused-exports] unused exports: {len(unused)}")
    for finding in unused:
        print(format_finding(finding, finding.reason))


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Detect top-level TypeScript exports that nothing in the repository references.",
        epilog=USAGE,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument(
        "--report",
        action="store_true",
        help="print every finding and always exit 0 (use this before enabling the gate)",
    )
    args = parser.parse_args()

    exports, entries, allowed, unused = scan()
    stale = stale_allowlist_entries(exports)

    if args.report:
        print_findings(exports, entries, allowed, unused)
        for relative, name in stale:
            print(f"[unused-exports] stale TEST_ONLY_ALLOW entry: {relative} {name}")
        return 0

    if unused or stale:
        print_findings(exports, entries, allowed, unused)
        for relative, name in stale:
            print(f"[unused-exports] stale TEST_ONLY_ALLOW entry: {relative} {name}")
        print("[unused-exports] FAIL: every hand-written export needs a caller outside the tests")
        print("       fix: add the caller, delete the export, or allowlist it with a reason")
        return 1

    print(
        f"[unused-exports] ok: {len(exports)} exports, {len(entries)} entry points, "
        f"{len(allowed)} allowlisted, 0 unused"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
