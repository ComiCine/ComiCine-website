"""Generate docs/lists/whitelist.txt from the hand-maintained own-ips.txt."""

from __future__ import annotations

import re
import sys
from pathlib import Path

try:
    from .check_gate_trust import parse_whitelist
except ImportError:
    from check_gate_trust import parse_whitelist

ROOT = Path(__file__).resolve().parent.parent
LISTS_DIR = ROOT / "docs" / "lists"
OWN_IPS = LISTS_DIR / "own-ips.txt"
WHITELIST = LISTS_DIR / "whitelist.txt"


def manual_entries(path: Path | None = None) -> list[str]:
    """Return non-empty entries, without comments, in source order."""
    path = path or OWN_IPS
    if not path.is_file():
        raise FileNotFoundError(f"whitelist source not found: {path}")
    entries: list[str] = []
    for raw in path.read_text(encoding="utf-8").splitlines():
        entry = re.sub(r"#.*$", "", raw).strip()
        if entry:
            entries.append(entry)
    parse_whitelist(entries)
    return entries


def render_whitelist(entries: list[str]) -> str:
    lines = [
        "# Generated by ops/sync_whitelist.py from docs/lists/own-ips.txt; do not edit.",
        "# Accepted entries: ASN/1-4294967295 and IP-CIDR/<address>/<prefix>.",
        "# CIDR ranges must be IPv4 /24-/32 or IPv6 /64-/128.",
        "# Edit own-ips.txt, then run the deployment or ops/sync_whitelist.py.",
        "",
        *entries,
    ]
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    try:
        entries = manual_entries()
        WHITELIST.write_text(render_whitelist(entries), encoding="utf-8")
    except (OSError, RuntimeError) as exc:
        print(f"sync_whitelist: failed: {exc}", file=sys.stderr)
        return 1
    try:
        display_path = WHITELIST.relative_to(ROOT)
    except ValueError:
        display_path = WHITELIST
    print(f"sync_whitelist: wrote {len(entries)} entries to {display_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
