// Generated by build.py. Do not edit by hand.
import { translations } from "../../_data/i18n";

export const onRequestGet = ({ params }: { params: Record<string, string> }) => {
  const lang = String((params as { lang?: string }).lang ?? "");
  // Use hasOwnProperty because translations is a plain object literal.
  // Direct lookup can return inherited members such as constructor,
  // toString, valueOf, or __proto__, incorrectly treating them as
  // supported languages. JSON.stringify on a function returns
  // undefined, which could produce a cached 200 response with an empty body.
  if (!Object.prototype.hasOwnProperty.call(translations, lang)) {
    return new Response(JSON.stringify({ error: "unsupported language" }), {
      status: 404,
      headers: { "Content-Type": "application/json" },
    });
  }
  const dict = translations[lang];
  return new Response(JSON.stringify(dict), {
    status: 200,
    headers: { "Content-Type": "application/json; charset=utf-8", "Cache-Control": "public, max-age=86400" },
  });
};
